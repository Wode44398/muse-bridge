// Bridge-owned record of generated media. Each generation gets an id; the binary
// lives at <dir>/<id>.<ext> and its metadata at <dir>/<id>.json. Pure fs.
//
// Multi-user: every function takes an optional `dir` (defaults to the admin/global
// media dir). Per-user callers pass their own .bridge/media so a user's generated
// results land in — and are listed/served from — their own folder.
import { mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync, statSync, rmSync, renameSync } from 'node:fs';
import { ID_RE, writeJson } from './jsonfile.mjs';
import { randomUUID } from 'node:crypto';
import path from 'node:path';
import { DATA_ROOT } from './runtime/paths.mjs';

const ROOT = DATA_ROOT;
export const MEDIA = path.join(ROOT, 'media'); // admin / default media dir
mkdirSync(MEDIA, { recursive: true });

const metaFile = (id, dir) => path.join(dir, id + '.json');
export const mediaPath = (id, ext, dir = MEDIA) => path.join(dir, id + '.' + ext);

export function newId() { return randomUUID(); }

// Persist the generated bytes + a metadata record. ext e.g. 'mp4'.
export function save(id, buf, ext, meta, dir = MEDIA) {
  if (!ID_RE.test(id)) throw new Error('bad media id');
  try { mkdirSync(dir, { recursive: true }); } catch {}
  writeFileSync(mediaPath(id, ext, dir), buf);
  const rec = { id, ext, kind: 'video', created: Date.now(), ...meta };
  writeJson(metaFile(id, dir), rec);
  // 预热缩略图（fire-and-forget）：生成完成时顺手出两档衍生图，首次打开历史不用现做
  derivedFor(id, dir, 'thumb').catch(() => {});
  derivedFor(id, dir, 'preview').catch(() => {});
  return rec;
}

export function get(id, dir = MEDIA) {
  if (!ID_RE.test(id)) return null;
  if (!existsSync(metaFile(id, dir))) return null;
  try { return JSON.parse(readFileSync(metaFile(id, dir), 'utf8')); } catch { return null; }
}

// Resolve an id to its on-disk binary path, guarding traversal within `dir`.
export function fileFor(id, dir = MEDIA) {
  const rec = get(id, dir);
  if (!rec) return null;
  const f = mediaPath(id, rec.ext || 'mp4', dir);
  if (!path.resolve(f).startsWith(path.resolve(dir) + path.sep)) return null;
  return existsSync(f) ? f : null;
}

// List media records in `dir`, optionally filtered by kind ('video' | 'image' | ...).
export function list(kind, dir = MEDIA) {
  let names = [];
  try { names = readdirSync(dir).filter((n) => n.endsWith('.json')); } catch {}
  const out = [];
  for (const n of names) {
    try {
      const rec = JSON.parse(readFileSync(path.join(dir, n), 'utf8'));
      const k = rec.kind || 'video';
      if (kind && k !== kind) continue;
      const st = statSync(path.join(dir, n));
      out.push({ id: rec.id, title: rec.prompt || '(无提示词)', model: rec.model || '', kind: k, ext: rec.ext || 'mp4', mtime: st.mtimeMs });
    } catch {}
  }
  return out.sort((a, b) => b.mtime - a.mtime);
}

export function remove(id, dir = MEDIA) {
  if (!ID_RE.test(id)) return false;
  const rec = get(id, dir);
  try {
    if (rec) rmSync(mediaPath(id, rec.ext || 'mp4', dir), { force: true });
    rmSync(metaFile(id, dir), { force: true });
    for (const s of ['.thumb.webp', '.prev.webp']) rmSync(path.join(dir, id + s), { force: true });  // 衍生缩略图一并清
    return true;
  } catch { return false; }
}

// —— 对话式图像：会话分组 ——
// 每张图仍是独立 media 文件，但同一条"连续修改"链共享一个 sessionId（meta.sessionId）。
// 历史抽屉按 sessionId 归并成一条会话，点开能还原整链续改。无 sessionId 的旧图/单发图
// 各自成单例会话（key=自身 id）——老数据天然兼容、点开退化为单轮，零迁移。
// 全部 fs 派生，不另存索引文件。

// 扫一遍 image 记录按 sessionId 归并。返回每条会话：
//   id      = 会话 key（sessionId，旧图为自身 id）——点开/删除按它
//   coverId = 链上最新一张图的 id——缩略图按它（看到的是最后改好的版本）
//   title   = 链上最早一轮的提示词（"原本"那条，便于回找）
//   count   = 链上图数；mtime = 最新一张的 mtime（排序用）
export function listImageChats(dir = MEDIA) {
  let names = [];
  try { names = readdirSync(dir).filter((n) => n.endsWith('.json')); } catch {}
  const groups = new Map();
  for (const n of names) {
    let rec, st;
    try { rec = JSON.parse(readFileSync(path.join(dir, n), 'utf8')); st = statSync(path.join(dir, n)); } catch { continue; }
    if ((rec.kind || 'video') !== 'image') continue;
    const key = rec.sessionId || rec.id;
    const created = rec.created || st.mtimeMs;
    let g = groups.get(key);
    if (!g) { g = { id: key, coverId: rec.id, coverAt: created, title: rec.prompt || '(无提示词)', titleAt: created, count: 0, mtime: st.mtimeMs }; groups.set(key, g); }
    g.count++;
    if (st.mtimeMs > g.mtime) g.mtime = st.mtimeMs;
    if (created >= g.coverAt) { g.coverAt = created; g.coverId = rec.id; }                       // 封面=最新
    if (created <= g.titleAt) { g.titleAt = created; g.title = rec.prompt || g.title; }          // 标题=最早
  }
  return [...groups.values()]
    .map((g) => ({ id: g.id, coverId: g.coverId, title: g.title, count: g.count, mtime: g.mtime }))
    .sort((a, b) => b.mtime - a.mtime);
}

// 还原一条会话的轮次（oldest→newest）：[{ userText, imageId }]。续改时前端原样回传当 prior。
export function loadImageChat(key, dir = MEDIA) {
  if (!ID_RE.test(key)) return null;
  let names = [];
  try { names = readdirSync(dir).filter((n) => n.endsWith('.json')); } catch {}
  const rows = [];
  for (const n of names) {
    let rec, st;
    try { rec = JSON.parse(readFileSync(path.join(dir, n), 'utf8')); st = statSync(path.join(dir, n)); } catch { continue; }
    if ((rec.kind || 'video') !== 'image') continue;
    if ((rec.sessionId || rec.id) !== key) continue;
    rows.push({ userText: rec.prompt || '', imageId: rec.id, at: rec.created || st.mtimeMs, batchId: rec.batchId, batchIndex: rec.batchIndex || 0,
      output: { id: rec.id, width: rec.width, height: rec.height, steps: rec.steps, seed: rec.seed, seconds: rec.seconds, cfg: rec.cfg, hasAlpha: rec.hasAlpha } });
  }
  if (!rows.length) return null;
  rows.sort((a, b) => a.at - b.at);
  const turns = [], batches = new Map();
  for (const row of rows) {
    let turn = row.batchId && batches.get(row.batchId);
    if (!turn) {
      turn = { userText: row.userText, imageId: row.imageId, outputs: [] };
      turns.push(turn); if (row.batchId) batches.set(row.batchId, turn);
    }
    turn.outputs.push({ ...row.output, batchIndex: row.batchIndex });
  }
  for (const turn of turns) { turn.outputs.sort((a, b) => a.batchIndex - b.batchIndex); turn.imageId = turn.outputs[0].id; }
  return { id: key, turns };
}

// 删整条会话（链上每张图连同衍生缩略图一并清）。
export function removeImageChat(key, dir = MEDIA) {
  if (!ID_RE.test(key)) return false;
  let names = [];
  try { names = readdirSync(dir).filter((n) => n.endsWith('.json')); } catch {}
  let any = false;
  for (const n of names) {
    let rec;
    try { rec = JSON.parse(readFileSync(path.join(dir, n), 'utf8')); } catch { continue; }
    if ((rec.kind || 'video') !== 'image') continue;
    if ((rec.sessionId || rec.id) !== key) continue;
    if (remove(rec.id, dir)) any = true;
  }
  return any;
}

// —— 衍生缩略图（sharp，懒生成 + 落盘缓存）——
// 背景：4K PNG 单张 ~20MB，历史网格 28 张 = 手机瞬间拉 ~500MB，WebView 直接全员碎图。
// 两档：thumb=320px(webp q70, ~10-30KB, 网格用) / preview=1280px(webp q80, ~100-400KB, 对话流大图用)。
// sharp 懒 import；任何失败返回 null → 调用方回退原图（行为退化为现状，不致命）。
// gif 跳过（缩略会丢动画）；并发请求同一张图用 in-flight Map 去重；tmp+rename 原子落盘。
const DERIVED = { thumb: { suffix: '.thumb.webp', size: 320, q: 70 }, preview: { suffix: '.prev.webp', size: 1280, q: 80 } };
const DERIVABLE = new Set(['png', 'jpg', 'jpeg', 'webp']);
// 视频：ffmpeg 抽一帧 → sharp 出两档海报图。手机 WebView 的 <video preload=metadata>
// 网格会撞解码器数量上限（多元素抢解码器 → 白块/碎图），网格必须用 <img> 海报。
const VIDEO_DERIVABLE = new Set(['mp4', 'webm']);
const _deriving = new Map();

// ffmpeg 在 0.2s 处抽一帧（最长边 1280）。ffmpeg 不存在/失败时 reject，调用方回退。
function extractFrame(src, framePng) {
  return new Promise((resolve, reject) => {
    import('node:child_process').then(({ spawn }) => {
      const p = spawn('ffmpeg', ['-y', '-ss', '0.2', '-i', src, '-frames:v', '1', '-vf', "scale='min(1280,iw)':-2", framePng], { windowsHide: true });
      p.on('error', reject);
      p.stderr.on('data', () => {});   // 消费掉避免管道阻塞
      p.on('close', (c) => (c === 0 && existsSync(framePng)) ? resolve() : reject(new Error('ffmpeg exit ' + c)));
    }, reject);
  });
}

export async function derivedFor(id, dir = MEDIA, variant) {
  const spec = DERIVED[variant];
  if (!spec || !ID_RE.test(id)) return null;
  const rec = get(id, dir);
  const ext = String(rec && rec.ext || '').toLowerCase();
  const isImg = DERIVABLE.has(ext), isVid = VIDEO_DERIVABLE.has(ext);
  if (!rec || (!isImg && !isVid)) return null;
  const src = fileFor(id, dir);
  if (!src) return null;
  const out = path.join(dir, id + spec.suffix);
  if (existsSync(out)) return out;
  if (_deriving.has(out)) return _deriving.get(out);
  const job = (async () => {
    try {
      const sharp = (await import('sharp')).default;
      let input = src;
      let frameTmp = null;
      if (isVid) {
        // 视频：先抽帧；一次抽帧顺手把两档都生成（省一次 ffmpeg）
        frameTmp = path.join(dir, id + '.frame.png');
        await extractFrame(src, frameTmp);
        input = frameTmp;
      }
      const makeOne = async (s) => {
        const o = path.join(dir, id + s.suffix);
        if (existsSync(o)) return;
        await sharp(input).rotate()
          .resize(s.size, s.size, { fit: 'inside', withoutEnlargement: true })
          .webp({ quality: s.q })
          .toFile(o + '.tmp');
        renameSync(o + '.tmp', o);
      };
      if (isVid) { await makeOne(DERIVED.thumb); await makeOne(DERIVED.preview); }
      else await makeOne(spec);
      if (frameTmp) { try { rmSync(frameTmp, { force: true }); } catch {} }
      return existsSync(out) ? out : null;
    } catch (err) {
      try { rmSync(out + '.tmp', { force: true }); } catch {}
      try { rmSync(path.join(dir, id + '.frame.png'), { force: true }); } catch {}
      console.error('[media] thumb failed:', id.slice(0, 8), String(err && err.message || err).slice(0, 120));
      return null;
    } finally { _deriving.delete(out); }
  })();
  _deriving.set(out, job);
  return job;
}
