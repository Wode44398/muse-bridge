// native host 看护的回归：只换引号里的 exe 路径、其余原样；已对就不写；认不出的格式不碰。

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { ensureChromeNativeHost, preferredNativeHostExe } from './chrome-native-host.mjs';

const BODY = (exe) => '@echo off\nREM Chrome native host wrapper script\nREM Generated by Claude Code - do not edit manually\n'
  + `"${exe}" "--chrome-native-host"`;

function withBat(content, fn) {
  const dir = mkdtempSync(path.join(os.tmpdir(), 'cfc-host-'));
  const bat = path.join(dir, 'chrome-native-host.bat');
  if (content != null) writeFileSync(bat, content, 'utf8');
  try { return fn(bat); } finally { rmSync(dir, { recursive: true, force: true }); }
}

const onWin = process.platform === 'win32';

test('改写成约定的 exe，其余内容一字不动', { skip: !onWin }, () => {
  withBat(BODY('C:\\old\\sdk\\claude.exe'), (bat) => {
    const r = ensureChromeNativeHost({ bat, exe: 'C:\\Users\\x\\AppData\\Roaming\\Claude\\claude-code\\2.1.280\\claude.exe' });
    assert.equal(r.changed, true);
    assert.equal(readFileSync(bat, 'utf8'), BODY('C:\\Users\\x\\AppData\\Roaming\\Claude\\claude-code\\2.1.280\\claude.exe'));
  });
});

test('已经指向约定 exe（大小写不同）时不写', { skip: !onWin }, () => {
  withBat(BODY('C:\\A\\claude.exe'), (bat) => {
    const r = ensureChromeNativeHost({ bat, exe: 'c:\\a\\CLAUDE.exe' });
    assert.equal(r.changed, false);
  });
});

test('没有 .bat / 认不出的格式 / 找不到 exe 都跳过、不抛错', { skip: !onWin }, () => {
  withBat(null, (bat) => assert.equal(ensureChromeNativeHost({ bat, exe: 'C:\\a.exe' }).skipped, 'no-bat'));
  withBat('@echo off\nsomething else\n', (bat) => assert.equal(ensureChromeNativeHost({ bat, exe: 'C:\\a.exe' }).skipped, 'unrecognized'));
  withBat(BODY('C:\\old.exe'), (bat) => assert.equal(ensureChromeNativeHost({ bat, exe: null }).skipped, 'no-exe'));
});

test('本机能找到一个真实存在的首选 exe', { skip: !onWin }, () => {
  const exe = preferredNativeHostExe();
  assert.ok(exe && /claude\.exe$/i.test(exe), String(exe));
});
