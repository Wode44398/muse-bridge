// bridge 替后台子代理发的续接消息（见 background.mjs）。单独一个没有依赖的文件：
// 历史回放（events.mjs）要认它，而 events.mjs 也被前端的单测直接引用，不能带进核心模块的依赖。

// 续接消息的原文。它在 agy 的会话历史里是一条用户消息，回放时按这句原文认出来、不当成用户说的话显示。
// 措辞要点：这条消息到的时候，agy 会先把积压的回报交给模型（模型往往当场就把结果说了），再把这条当作用户输入交给它——
// 不写明「说过就别重复」的话，模型会把同一份结果再讲一遍（真 agy 实测）。
export const AGY_WAKE_PROMPT = '（bridge 自动续接，不是用户发的话：后台子代理的回报刚送达。如果你还没把它的结果告诉用户，现在根据回报继续、把结果告诉用户；如果刚才已经说过了，就不要重复，也不用回应这条，直接结束这一轮。）';

export function isWakePrompt(text) {
  return String(text ?? '').trim() === AGY_WAKE_PROMPT;
}
