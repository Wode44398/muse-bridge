  // disconnects, the app keeps running.
  attached = false;
  // 桌面壳模式：target 由壳的 broker 创建/关闭（真 WebContentsView，用户与 agent 同屏）。
  // Electron 调试端口上还有 bridge UI 与别家会话的 target——list/tabs 只认 ownedTargets。
