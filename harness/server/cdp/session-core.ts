  // 隔离存储（按会话开关）：共享宿主里本会话独占的浏览上下文——cookie / 存储 / 缓存都不和别的会话共用，关掉即清空。
  // "" = 宿主的默认上下文（持久配置档，登录态大家共享）。
  browserContextId = "";
